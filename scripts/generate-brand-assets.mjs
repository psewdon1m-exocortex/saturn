import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(path.join(root, "packages/shares/package.json"));
const sharp = require("sharp");
const source = path.join(root, ".src/saturn-devouring-his-son.png");
const publicDirectory = path.join(root, "apps/web/public");
const iconsDirectory = path.join(publicDirectory, "assets");
const logoDirectory = path.join(root, "apps/web/src/assets");
const metadata = await sharp(source).metadata();
assert.equal(metadata.width, metadata.height, "The approved artwork must be square; never crop it implicitly");
assert.ok(metadata.width >= 512, "The artwork must support the largest export without upscaling");
await fs.mkdir(iconsDirectory, { recursive: true });
await fs.mkdir(logoDirectory, { recursive: true });

const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
const exports = new Map();
const icons = {};
for (const size of [16, 32, 48, 64, 128, 180, 192, 256, 512]) {
  const bytes = await sharp(source).resize(size, size, { fit: "contain", kernel: sharp.kernel.lanczos3 })
    .toColourspace("srgb").png({ compressionLevel: 9, palette: false }).toBuffer();
  const filename = `saturn-icon-${size}-${digest(bytes).slice(0, 12)}.png`;
  await fs.writeFile(path.join(iconsDirectory, filename), bytes);
  exports.set(size, bytes);
  icons[size] = `/assets/${filename}`;
}

// PNG-backed ICO frames preserve the same artwork at each native icon size.
const frames = [16, 32, 48, 64, 128, 256];
const header = Buffer.alloc(6 + frames.length * 16);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(frames.length, 4);
let offset = header.length;
for (let index = 0; index < frames.length; index += 1) {
  const size = frames[index];
  const bytes = exports.get(size);
  const entry = 6 + index * 16;
  header.writeUInt8(size === 256 ? 0 : size, entry);
  header.writeUInt8(size === 256 ? 0 : size, entry + 1);
  header.writeUInt16LE(1, entry + 4);
  header.writeUInt16LE(32, entry + 6);
  header.writeUInt32LE(bytes.length, entry + 8);
  header.writeUInt32LE(offset, entry + 12);
  offset += bytes.length;
}
const ico = Buffer.concat([header, ...frames.map((size) => exports.get(size))]);
const icoFilename = `saturn-favicon-${digest(ico).slice(0, 12)}.ico`;
await fs.writeFile(path.join(iconsDirectory, icoFilename), ico);
await fs.writeFile(path.join(publicDirectory, "saturn-favicon.png"), exports.get(32));
await fs.writeFile(path.join(logoDirectory, "saturn-logo.png"), exports.get(512));

const htmlPath = path.join(root, "apps/web/index.html");
const html = await fs.readFile(htmlPath, "utf8");
const eol = html.includes("\r\n") ? "\r\n" : "\n";
const iconTags = [
  "    <!-- Saturn brand icons: generated by scripts/generate-brand-assets.mjs -->",
  `    <link rel="icon" type="image/x-icon" sizes="16x16 32x32 48x48 64x64 128x128 256x256" href="/assets/${icoFilename}" />`,
  `    <link rel="icon" type="image/png" sizes="16x16" href="${icons[16]}" />`,
  `    <link rel="icon" type="image/png" sizes="32x32" href="${icons[32]}" />`,
  `    <link rel="icon" type="image/png" sizes="192x192" href="${icons[192]}" />`,
  `    <link rel="apple-touch-icon" sizes="180x180" href="${icons[180]}" />`,
  "    <!-- End Saturn brand icons -->",
].join(eol);
const existingBlock = /    <!-- Saturn brand icons:[\s\S]*?    <!-- End Saturn brand icons -->/;
const previousTag = /    <link rel="icon" type="image\/png" sizes="1254x1254" href="\/saturn-favicon\.png" \/>/;
assert.ok(existingBlock.test(html) || previousTag.test(html), "The known icon block must exist before updating HTML");
await fs.writeFile(htmlPath, html.replace(existingBlock.test(html) ? existingBlock : previousTag, iconTags));
process.stdout.write(JSON.stringify({ source: path.relative(root, source), sourceSha256: digest(await fs.readFile(source)),
  logo: "apps/web/src/assets/saturn-logo.png", icons, ico: `/assets/${icoFilename}` }, null, 2) + "\n");
